export function countryNames(lang: string, overrides: Record<string, string> = {}): string[] {
  const dn = new Intl.DisplayNames([lang], { type: 'region' });
  return CODES.map((c) => overrides[c] ?? dn.of(c) ?? c).sort((a, b) => a.localeCompare(b, lang));
}
